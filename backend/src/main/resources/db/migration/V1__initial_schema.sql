-- Initial schema (matches the entities in com.pitercoding.backend.model).

CREATE TABLE programs (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(255) NOT NULL,
    active BOOLEAN      NOT NULL
);

CREATE TABLE teams (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(255) NOT NULL,
    active BOOLEAN      NOT NULL
);

CREATE TABLE languages (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(255) NOT NULL,
    active BOOLEAN      NOT NULL
);

CREATE TABLE activities (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(255) NOT NULL,
    active BOOLEAN      NOT NULL
);

CREATE TABLE subactivities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT       NOT NULL REFERENCES activities (id),
    name        VARCHAR(255) NOT NULL,
    active      BOOLEAN      NOT NULL
);

CREATE TABLE employees (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    email      VARCHAR(255) NOT NULL UNIQUE,
    department VARCHAR(255),
    role       VARCHAR(255),
    active     BOOLEAN      NOT NULL
);

CREATE TABLE workdays (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT       NOT NULL REFERENCES employees (id),
    date        DATE         NOT NULL,
    started_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP(6) WITH TIME ZONE,
    status      VARCHAR(255) NOT NULL CHECK (status IN ('OPEN', 'FINISHED')),
    UNIQUE (employee_id, date)
);

CREATE TABLE activity_entries (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_day_id      BIGINT       NOT NULL REFERENCES workdays (id),
    program_id       BIGINT       NOT NULL REFERENCES programs (id),
    team_id          BIGINT       NOT NULL REFERENCES teams (id),
    language_id      BIGINT       NOT NULL REFERENCES languages (id),
    activity_id      BIGINT       NOT NULL REFERENCES activities (id),
    subactivity_id   BIGINT       NOT NULL REFERENCES subactivities (id),
    started_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at      TIMESTAMP(6) WITH TIME ZONE,
    duration_seconds BIGINT,
    note             VARCHAR(255)
);
